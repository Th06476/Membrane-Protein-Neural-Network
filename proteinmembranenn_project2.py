def clean_sequence(seq):
    """Upper-case and strip anything that is not a letter (whitespace, '*', digits...)."""
    if not isinstance(seq, str):
        return ""
    return re.sub(r"[^A-Z]", "", seq.upper())


def parse_labels(series):
    """Accept 0/1, True/False, yes/no style labels for the in_membrane column."""
    mapping = {"1": 1, "0": 0, "true": 1, "false": 0, "yes": 1, "no": 0, "y": 1, "n": 0}
    as_str = series.astype(str).str.strip().str.lower()
    as_str = as_str.str.replace(r"\.0$", "", regex=True)
    labels = as_str.map(mapping)
    if labels.isna().any():
        bad = series[labels.isna()].unique()[:5]
        raise ValueError(f"Unrecognised values in 'in_membrane' column: {bad}")
    return labels.astype(np.float32).values


