def best_f1_threshold(y, p):
    """Decision threshold that maximises F1 on the validation split."""
    prec, rec, thr = precision_recall_curve(y, p)
    if len(thr) == 0:
        return 0.5
    f1 = 2 * prec[:-1] * rec[:-1] / (prec[:-1] + rec[:-1] + 1e-12)
    return float(thr[int(np.argmax(f1))])


def compute_metrics(y, p, threshold):
    pred = (p >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return {
        "auroc": safe_auc(y, p),
        "auprc": average_precision_score(y, p) if len(np.unique(y)) > 1 else float("nan"),
        "accuracy": accuracy_score(y, pred),
        "balanced_accuracy": balanced_accuracy_score(y, pred),
        "precision": precision_score(y, pred, zero_division=0),
        "recall_sensitivity": recall_score(y, pred, zero_division=0),
        "specificity": tn / (tn + fp) if (tn + fp) > 0 else float("nan"),
        "f1": f1_score(y, pred, zero_division=0),
        "mcc": matthews_corrcoef(y, pred),
        "brier_score": brier_score_loss(y, p),
        "threshold": threshold,
        "tp": int(tp), "fp": int(fp), "tn": int(tn), "fn": int(fn),
    }


CI_KEYS = ["auroc", "auprc", "accuracy", "balanced_accuracy", "precision",
           "recall_sensitivity", "specificity", "f1", "mcc"]


def bootstrap(y, p_ffnn, p_cnn, thr_ffnn, thr_cnn, n_boot, seed):
    """
    Percentile bootstrap 95% CIs for every metric of both models, resampling the same
    proteins for both (paired), plus the distribution of AUROC(stage 2) - AUROC(stage 1).
    """
    rng = np.random.default_rng(seed)
    n = len(y)
    samples = {"ffnn": {k: [] for k in CI_KEYS}, "cnn": {k: [] for k in CI_KEYS}}
    deltas = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        if len(np.unique(y[idx])) < 2:
            continue
        m1 = compute_metrics(y[idx], p_ffnn[idx], thr_ffnn)
        m2 = compute_metrics(y[idx], p_cnn[idx], thr_cnn)
        for k in CI_KEYS:
            samples["ffnn"][k].append(m1[k])
            samples["cnn"][k].append(m2[k])
        deltas.append(m2["auroc"] - m1["auroc"])

    cis = {
        model: {k: [float(np.nanpercentile(v, 2.5)), float(np.nanpercentile(v, 97.5))]
                for k, v in d.items()}
        for model, d in samples.items()
    }
    deltas = np.array(deltas)
    p_value = min(1.0, 2 * min(np.mean(deltas <= 0), np.mean(deltas >= 0)))
    delta_summary = {
        "delta_auroc_ci95": [float(np.percentile(deltas, 2.5)), float(np.percentile(deltas, 97.5))],
        "bootstrap_p_value_two_sided": float(p_value),
        "n_bootstrap": int(len(deltas)),
    }
    return cis, delta_summary


def plot_curves(y, p_ffnn, p_cnn, path):
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5))
    for label, p, color in [("Stage 1 FFNN", p_ffnn, "#4C72B0"), ("Stage 2 CNN (stacked)", p_cnn, "#DD8452")]:
        fpr, tpr, _ = roc_curve(y, p)
        axes[0].plot(fpr, tpr, color=color, lw=2, label=f"{label} (AUROC={roc_auc_score(y, p):.3f})")
        prec, rec, _ = precision_recall_curve(y, p)
        axes[1].plot(rec, prec, color=color, lw=2,
                     label=f"{label} (AP={average_precision_score(y, p):.3f})")
    axes[0].plot([0, 1], [0, 1], "--", color="grey", lw=1)
    axes[0].set(xlabel="False positive rate", ylabel="True positive rate", title="ROC curve (held-out test split)")
    axes[1].axhline(y.mean(), ls="--", color="grey", lw=1, label=f"Prevalence ({y.mean():.2f})")
    axes[1].set(xlabel="Recall", ylabel="Precision", title="Precision-recall curve (held-out test split)")
    for ax in axes:
        ax.legend(loc="lower right" if ax is axes[0] else "lower left", fontsize=8)
        ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_confusion(m_ffnn, m_cnn, path):
    fig, axes = plt.subplots(1, 2, figsize=(9, 4))
    for ax, (title, m) in zip(axes, [("Stage 1 FFNN", m_ffnn), ("Stage 2 CNN (stacked)", m_cnn)]):
        cm = np.array([[m["tn"], m["fp"]], [m["fn"], m["tp"]]])
        ax.imshow(cm, cmap="Blues")
        for i in range(2):
            for j in range(2):
                ax.text(j, i, cm[i, j], ha="center", va="center",
                        color="white" if cm[i, j] > cm.max() / 2 else "black", fontsize=13)
        ax.set_xticks([0, 1], ["Not membrane", "Membrane"])
        ax.set_yticks([0, 1], ["Not membrane", "Membrane"])
        ax.set(xlabel="Predicted", ylabel="Actual", title=f"{title}\nthreshold={m['threshold']:.3f}")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


