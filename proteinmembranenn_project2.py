def one_hot_encode(sequences, max_len):
    """
    One-hot encode protein sequences.

    Returns a uint8 tensor of shape (n_sequences, 20, max_len). Sequences longer than
    max_len are truncated, shorter ones are zero-padded, and non-standard residues
    (X, B, Z, U, O ...) are left as all-zero columns. uint8 keeps memory low; batches
    are converted to float when they go into the network.
    """
    encoded = np.zeros((len(sequences), len(AMINO_ACIDS), max_len), dtype=np.uint8)
    for i, seq in enumerate(sequences):
        for pos, aa in enumerate(seq[:max_len]):
            idx = AA_INDEX.get(aa)
            if idx is not None:
                encoded[i, idx, pos] = 1
    return torch.from_numpy(encoded)


def BuildFeatures(sequences, hydrophobic=HYDROPHOBIC, run_thresholds=RUN_THRESHOLDS):
    """
    Hand-crafted hydrophobicity features, computed with an explicit loop over each residue.

    For every sequence:
      hydrophobic_ratio          = (# hydrophobic residues) / (sequence length)
      n_hydrophobic_runs_ge{T}   = number of stretches of consecutive hydrophobic residues
                                   that are at least T residues long, for each T in
                                   run_thresholds
    """
    rows = []
    for seq in sequences:
        n_hydrophobic = 0
        current_run = 0
        runs = []                       # lengths of every consecutive hydrophobic stretch

        for aa in seq:
            if aa in hydrophobic:
                n_hydrophobic += 1
                current_run += 1
            else:
                if current_run > 0:
                    runs.append(current_run)
                current_run = 0
        if current_run > 0:             # sequence ended inside a hydrophobic stretch
            runs.append(current_run)

        row = {"hydrophobic_ratio": n_hydrophobic / len(seq) if len(seq) > 0 else 0.0}
        for t in run_thresholds:
            count = 0
            for r in runs:
                if r >= t:
                    count += 1
            row[f"n_hydrophobic_runs_ge{t}"] = count
        rows.append(row)

    return pd.DataFrame(rows)



class MembraneFFNN(nn.Module):
    """Stage 1: fully connected feed-forward network with dropout."""

    def __init__(self, seq_input_dim, n_features, hidden_sizes, dropout):
        super().__init__()
        layers = []
        in_dim = seq_input_dim + n_features
        for h in hidden_sizes:
            layers += [nn.Linear(in_dim, h), nn.ReLU(), nn.Dropout(dropout)]
            in_dim = h
        layers.append(nn.Linear(in_dim, 1))
        self.net = nn.Sequential(*layers)

    def forward(self, x_seq, x_feat):
        x = torch.cat([x_seq.flatten(1), x_feat], dim=1)
        return self.net(x).squeeze(1)


class MembraneCNN(nn.Module):
    """
    Stage 2: 1-D CNN. Alternating Conv1d -> ReLU -> MaxPool1d blocks scan the one-hot
    sequence; a global max pool summarises it; the summary is joined with the
    hand-crafted features and the stage-1 probability before the dense head.
    """

    def __init__(self, seq_len, n_extra, filters, kernels, pool_size, dense_units, dropout):
        super().__init__()
        layers = []
        in_ch = len(AMINO_ACIDS)
        length = seq_len
        for f, k in zip(filters, kernels):
            layers += [nn.Conv1d(in_ch, f, kernel_size=k, padding=k // 2), nn.ReLU()]
            if length // pool_size >= 1:          # never pool the sequence away entirely
                layers.append(nn.MaxPool1d(pool_size))
                length //= pool_size
            in_ch = f
        self.conv = nn.Sequential(*layers)
        self.global_pool = nn.AdaptiveMaxPool1d(1)
        self.head = nn.Sequential(
            nn.Linear(in_ch + n_extra, dense_units),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(dense_units, 1),
        )

    def forward(self, x_seq, x_feat):
        z = self.global_pool(self.conv(x_seq)).squeeze(2)
        return self.head(torch.cat([z, x_feat], dim=1)).squeeze(1)


def build_ffnn(params, seq_len, n_features):
    hidden = [params[f"units_l{i}"] for i in range(params["n_layers"])]
    return MembraneFFNN(len(AMINO_ACIDS) * seq_len, n_features, hidden, params["dropout"]).to(DEVICE)


def build_cnn(params, seq_len, n_extra):
    filters = [params[f"filters_b{i}"] for i in range(params["n_blocks"])]
    kernels = [params[f"kernel_b{i}"] for i in range(params["n_blocks"])]
    return MembraneCNN(
        seq_len, n_extra, filters, kernels, params["pool_size"], params["dense_units"], params["dropout"]
    ).to(DEVICE)


