def suggest_ffnn_params(trial):
    n_layers = trial.suggest_int("n_layers", 1, 3)
    params = {"n_layers": n_layers}
    for i in range(n_layers):
        params[f"units_l{i}"] = trial.suggest_categorical(f"units_l{i}", [32, 64, 128, 256, 512])
    params["dropout"] = trial.suggest_float("dropout", 0.1, 0.6)
    params["lr"] = trial.suggest_float("lr", 1e-4, 1e-2, log=True)
    params["weight_decay"] = trial.suggest_float("weight_decay", 1e-6, 1e-2, log=True)
    params["batch_size"] = trial.suggest_categorical("batch_size", [32, 64, 128])
    return params


def suggest_cnn_params(trial):
    n_blocks = trial.suggest_int("n_blocks", 1, 4)
    params = {"n_blocks": n_blocks}
    for i in range(n_blocks):
        params[f"filters_b{i}"] = trial.suggest_categorical(f"filters_b{i}", [16, 32, 64, 128])
        params[f"kernel_b{i}"] = trial.suggest_categorical(f"kernel_b{i}", [3, 5, 7, 9, 11, 15, 19])
    params["pool_size"] = trial.suggest_categorical("pool_size", [2, 3, 4])
    params["dense_units"] = trial.suggest_categorical("dense_units", [32, 64, 128])
    params["dropout"] = trial.suggest_float("dropout", 0.1, 0.6)
    params["lr"] = trial.suggest_float("lr", 1e-4, 1e-2, log=True)
    params["weight_decay"] = trial.suggest_float("weight_decay", 1e-6, 1e-2, log=True)
    params["batch_size"] = trial.suggest_categorical("batch_size", [32, 64, 128])
    return params


def run_study(name, suggest_fn, build_fn, train, val, args, pos_weight):
    def objective(trial):
        params = suggest_fn(trial)
        model = build_fn(params)
        _, val_auc, best_epoch = fit(
            model, train, val, params["lr"], params["weight_decay"], params["batch_size"],
            args.epochs, args.patience, pos_weight, trial=trial,
        )
        trial.set_user_attr("best_epoch", best_epoch)
        return val_auc

    def log(study, trial):
        if trial.state == optuna.trial.TrialState.COMPLETE:
            print(f"  [{name}] trial {trial.number:3d}  val AUROC={trial.value:.4f}  "
                  f"(best so far {study.best_value:.4f})")
        elif trial.state == optuna.trial.TrialState.PRUNED:
            print(f"  [{name}] trial {trial.number:3d}  pruned")

    study = optuna.create_study(
        direction="maximize",
        study_name=name,
        sampler=optuna.samplers.TPESampler(seed=args.seed),
        pruner=optuna.pruners.MedianPruner(n_startup_trials=5, n_warmup_steps=3),
    )
    study.optimize(objective, n_trials=args.ffnn_trials if name == "FFNN" else args.cnn_trials,
                   callbacks=[log])
    return study


