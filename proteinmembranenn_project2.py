def safe_auc(y, p):
    return roc_auc_score(y, p) if len(np.unique(y)) > 1 else 0.5


@torch.no_grad()
def predict_proba(model, seq, feat, batch_size=256):
    model.eval()
    out = []
    for i in range(0, len(seq), batch_size):
        xs = seq[i:i + batch_size].to(DEVICE).float()
        xf = feat[i:i + batch_size].to(DEVICE)
        out.append(torch.sigmoid(model(xs, xf)).cpu())
    return torch.cat(out).numpy()


def fit(model, train, val, lr, weight_decay, batch_size, max_epochs, patience, pos_weight,
        trial=None, fixed_epochs=None):
    """
    Train with AdamW and class-weighted BCE.
    - Normal mode: early-stop on validation AUROC and restore the best epoch's weights;
      report each epoch to Optuna so poor trials are pruned.
    - fixed_epochs mode: train for exactly that many epochs with no validation set
      (used for the out-of-fold stage-1 models).
    Returns (model, best_val_auroc, best_epoch).
    """
    seq_tr, feat_tr, y_tr = train
    loader = DataLoader(TensorDataset(seq_tr, feat_tr, y_tr), batch_size=batch_size, shuffle=True)
    opt = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=weight_decay)
    loss_fn = nn.BCEWithLogitsLoss(pos_weight=torch.tensor(pos_weight, device=DEVICE))

    n_epochs = fixed_epochs if fixed_epochs is not None else max_epochs
    best_auc, best_epoch, best_state, bad_epochs = -1.0, 0, None, 0

    for epoch in range(n_epochs):
        model.train()
        for xs, xf, yb in loader:
            xs, xf, yb = xs.to(DEVICE).float(), xf.to(DEVICE), yb.to(DEVICE)
            opt.zero_grad()
            loss = loss_fn(model(xs, xf), yb)
            loss.backward()
            opt.step()

        if fixed_epochs is not None:
            continue

        val_auc = safe_auc(val[2].numpy(), predict_proba(model, val[0], val[1]))
        if trial is not None:
            trial.report(val_auc, epoch)
            if trial.should_prune():
                raise optuna.TrialPruned()

        if val_auc > best_auc:
            best_auc, best_epoch, bad_epochs = val_auc, epoch, 0
            best_state = {k: v.detach().clone() for k, v in model.state_dict().items()}
        else:
            bad_epochs += 1
            if bad_epochs >= patience:
                break

    if best_state is not None:
        model.load_state_dict(best_state)
    return model, best_auc, best_epoch


