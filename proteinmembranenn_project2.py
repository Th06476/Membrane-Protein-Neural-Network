# Constants

AMINO_ACIDS = "ACDEFGHIKLMNPQRSTVWY"           # 20 standard residues -> 20 one-hot channels
AA_INDEX = {aa: i for i, aa in enumerate(AMINO_ACIDS)}

# Hydrophobic residues
HYDROPHOBIC = set("GPFAILV")

# BuildFeatures counts how many unbroken hydrophobic stretches are at least this long.
# ~18-20 residues is the length of a transmembrane helix; shorter thresholds catch
# partial / interrupted helices.
RUN_THRESHOLDS = (6, 10, 18)

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")



